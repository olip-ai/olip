// Writes the OLIP 3.0-draft JSON Schemas (draft 2020-12) to ../schemas/ and the action input schemas to ../schemas/actions/.
// The schemas are defined once, in reference/schemas.mjs. Run: node scripts/make-schemas.mjs
// (tests/schemas.test.mjs fails if the committed files differ from this output)
import { writeFileSync, mkdirSync, rmSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { SCHEMAS, INPUT_SCHEMAS } from "../reference/schemas.mjs";
import { ERRORS } from "../reference/lib/errors.mjs";

export const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const schemaFiles = () => ({
  ...Object.fromEntries(Object.entries(SCHEMAS).map(([n, s]) => [`${n}.schema.json`, s])),
  ...Object.fromEntries(Object.entries(INPUT_SCHEMAS).map(([id, s]) => [`actions/${id}.input.json`, s])),
});
// docs/ERROR_CATALOG.md is generated from the same table as the error schema enum and the A2A mapping.
export const errorCatalogMarkdown = () => ["# Error catalog (generated)", "", "Generated by `scripts/make-schemas.mjs` from `reference/lib/errors.mjs`. Do not edit by hand. Every error body is `{ olip_version, error: { code, message, retryable, details? }, correlation_id }`. MCP returns errors as tool results with `isError: true` and the same body. Hidden objects always answer `NOT_FOUND`, never a different code.", "",
  "| Code | HTTP | Retry with same key | A2A task state | Meaning |", "|---|---|---|---|---|",
  ...Object.values(ERRORS).map((e) => `| \`${e.code}\` | ${e.http} | ${e.retryable ? "yes" : "no"} | \`${e.a2a_task_state}\` | ${e.meaning} |`), ""].join("\n");
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(join(root, "docs"), { recursive: true });
  writeFileSync(join(root, "docs", "ERROR_CATALOG.md"), errorCatalogMarkdown());
  rmSync(join(root, "schemas"), { recursive: true, force: true });
  mkdirSync(join(root, "schemas", "actions"), { recursive: true });
  const files = schemaFiles();
  for (const [f, s] of Object.entries(files)) writeFileSync(join(root, "schemas", f), JSON.stringify(s, null, 2) + "\n");
  console.log(`wrote ${Object.keys(files).length} schema files`);
}
