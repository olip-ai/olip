// Generates the OLIP 0.2 fictional examples by running the reference endpoint (nothing is written by hand).
// Usage: node scripts/make-examples-0.2.mjs   -> writes examples-0.2/*.json
import { writeFileSync } from "node:fs";
import { createServer } from "node:http";
import { createOlipServer } from "../reference/server.mjs";
import { OlipClient, mockUserApproves } from "../reference/client.mjs";

const PUBLIC = "https://olip-mock.example.test";
const { server: olip } = createOlipServer();
await new Promise((r) => olip.listen(0, "127.0.0.1", r));
const base = `http://127.0.0.1:${olip.address().port}`;
const got = [];
const recv = createServer((q, s) => { let b = ""; q.on("data", (c) => (b += c)); q.on("end", () => { got.push(JSON.parse(b)); s.writeHead(204); s.end(); }); });
await new Promise((r) => recv.listen(0, "127.0.0.1", r));
const FX = await fetch(`${base}/mock/fixtures`).then((r) => r.json());
const A = new OlipClient(base, FX.clients.a); await A.login();
const cb = (await A.createBrief({ fictional: true, client: { name: "Pat Example (fictional)", email: "pat.example@example.test" }, location: { jurisdiction: "US-CA" }, matter: { code: "housing.landlord_tenant" }, summary: "Fictional: my landlord gave me an eviction notice." })).body.casebrief;
const pv = (await A.preview({ casebrief_id: cb.id, recipient_id: FX.professionals.direct_ok, fields: ["summary", "client.name", "client.email", "location.jurisdiction", "matter.code"], mode: "consumer_selected_listing", purpose: "request_initial_contact", selection: { by: "user" } })).body.preview;
const auth = (await mockUserApproves(base, pv, cb.client.email)).body.authorization;
const h = (await A.submit({ authorization_id: auth.authorization_id, consent_digest: auth.consent_digest })).body.handoff;
const sub = (await A.req("POST", `/olip/v0.2/handoffs/${h.handoff_id}/subscriptions`, { callback_url: `http://127.0.0.1:${recv.address().port}/olip-hook` })).body.subscription;
await A.cancel(h.handoff_id);
for (let i = 0; i < 40 && !got.length; i++) await new Promise((r) => setTimeout(r, 50));
const card = await fetch(`${base}/olip/v0.2/professionals/${FX.professionals.direct_ok}/intake-card`).then((r) => r.json());
const bindings = await fetch(`${base}/.well-known/olip-key-bindings.json`).then((r) => r.json());
const keys = await fetch(`${base}/.well-known/olip-keys.json`).then((r) => r.json());
// Replace local addresses with a reserved test domain. Signatures over objects that contained the local address no longer verify; that is stated in each example.
const fix = (o) => JSON.parse(JSON.stringify(o).replaceAll(base, PUBLIC).replace(/http:\/\/127\.0\.0\.1:\d+\/olip-hook/g, "https://agent-app.example.test/olip-hook"));
const note = (verifies) => verifies ? "Fictional example generated by the reference endpoint. The signature verifies with the keys in 20-keys.json." : "Fictional example generated by the reference endpoint. Local addresses were replaced with example.test after signing, so this signature does not verify; run the reference endpoint for one that does.";
const ex = {
  "20-keys.json": { schema: null, note: "JWKS with the recipient intake key and the host key (olip_key_role).", example: keys },
  "21-key-bindings.json": { schema: "0.2/key-bindings", note: note(true), example: bindings },
  "22-webhook-subscription.json": { schema: "0.2/webhook-subscription", note: "Fictional example generated by the reference endpoint.", example: fix(sub) },
  "23-status-webhook.json": { schema: "0.2/status-webhook", note: note(true), example: got[0] },
  "24-intake-capability-card.json": { schema: "0.2/intake-capability-card", note: note(false), example: fix(card) },
};
for (const [f, v] of Object.entries(ex)) writeFileSync(new URL(`../examples-0.2/${f}`, import.meta.url), JSON.stringify(v, null, 2) + "\n");
recv.close(); olip.close();
console.log(`wrote ${Object.keys(ex).length} examples`);
